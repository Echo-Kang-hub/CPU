###############################################################################
# 斐波那契数列计算 —— 流水线CPU功能验证程序
#
# 功能说明：
#   读取拨码开关 SW[14:10] 作为输入 n (0~31)，
#   递归计算 fib(n)，结果输出到 7段数码管 (SEG7)。
#
# 流水线CPU特性覆盖：
#   [1] 数据冒险 (Data Hazard):
#       - 算术指令间 RAW 相关: lw→srli→andi, lw→add, lw→addi 等
#       - load-use 冒险: lw→srli (相隔1条), lw→bge (相隔1条)
#   [2] 控制冒险 (Control Hazard):
#       - 条件分支: bge (fib基线判断)
#       - 无条件跳转: jal (递归调用), jalr (函数返回)
#       - 每次递归调用都产生控制流跳转
#   [3] 递归深度: n 最大 31，递归深度可达 31 层，充分测试栈操作和跳转
#   [4] 寄存器堆正确性: x1(栈指针)、x5(返回地址)、x6(n)、x7(结果) 各司其职
#
# 硬件设置 (FPGA):
#   - xgriscv_fpga_top.v 中 `localparam USE_SW15_CPU_CLK = 1'b0;`
#     (不开单步调试，CPU 直接运行，看最终结果；若需单步可改 1'b1)
#   - SW[14:10] = 输入 n (0~31)
#   - SW[5:0]   = 选择 MULTI_CH32 显示通道，推荐 SW[5:0]=6'b000000
#     (此时 SEG7 显示 CPU 写入 SEG7 寄存器的值，即 fib 结果)
#   - SEG7 显示 fib(n) 的十六进制结果
#
# 验证方法 (不开单步，直接看结果):
#   1. 设置 SW[14:10] = n (例如 n=5 → SW[14:10]=5'b00101)
#   2. 观察 SEG7 显示值，对照下方参考表
#   3. 逐一验证多个 n 值以确保正确性
#
# 预期结果参考 (十六进制):
#   n   fib(n)     n   fib(n)     n   fib(n)
#   0   0x000001   11  0x000090   22  0x006FF1
#   1   0x000001   12  0x0000E9   23  0x00B520
#   2   0x000002   13  0x000179   24  0x012511
#   3   0x000003   14  0x000262   25  0x01DA31
#   4   0x000005   15  0x0003DB   26  0x02FF42
#   5   0x000008   16  0x00063D   27  0x04D973
#   6   0x00000D   17  0x000A18   28  0x07D8B5
#   7   0x000015   18  0x001055   29  0x0CB228
#   8   0x000022   19  0x001A6D   30  0x148ADD
#   9   0x000037   20  0x002AC2   31  0x213D05
#   10  0x000059   21  0x00452F
#
# 寄存器分配:
#   x1  (= sp)   栈指针 (向下增长)
#   x5           返回地址寄存器 (不用 x1 做链接寄存器，避免与栈指针冲突)
#   x6           输入 n (来自 SW[14:10])
#   x7           fib(n) 结果 / 递归返回值
#   x8           暂存 fib(n-2) 用于加法
#   x31          I/O 基地址 0xFFFF0000
###############################################################################

    lui     x31, 0xFFFF0        # x31 = 0xFFFF0000 (I/O基地址)
    addi    x1, x0, -4          # x1 = -4 (栈指针初始化为 0xFFFFFFFC)

main:
    lw      x6, 0x004(x31)      # x6 = SW[15:0] (读拨码开关)
    srli    x6, x6, 10          # 右移10位，将 SW[14:10] 移到低5位
    andi    x6, x6, 0x01F       # 取低5位 = n (0~31)
    jal     x5, fib             # 调用 fib(n)，返回地址存 x5
    sw      x7, 0x00C(x31)      # 将 fib(n) 写入 SEG7 显示 (0xFFFF000C)
    jal     x0, main            # 无限循环，持续读取开关并计算

fib:
    # fib(n): 递归计算斐波那契数列
    # 参数: x6 = n
    # 返回值: x7 = fib(n)
    # 返回地址: x5
    addi    x7, x0, 1           # x7 = 1 (fib(0)=fib(1)=1)
    bge     x7, x6, ret         # if (1 >= n) 即 n<=1，直接返回 x7=1
    addi    x1, x1, -8          # 栈分配 8 字节
    sw      x5, 4(x1)           # 保存返回地址
    addi    x6, x6, -1          # n = n - 1
    jal     x5, fib             # fib(n-1)
    sw      x7, 0(x1)           # 保存 fib(n-1) 到栈上
    addi    x6, x6, -1          # n = n - 2 (注意 x6 已被 fib(n-1) 修改为 n-2)
    jal     x5, fib             # fib(n-2)
    lw      x8, 0(x1)           # x8 = fib(n-1) (从栈恢复)
    add     x7, x7, x8          # x7 = fib(n-2) + fib(n-1)
    addi    x6, x6, 2           # 恢复 x6 = n (修复被递归破坏的 n)
    lw      x5, 4(x1)           # 恢复返回地址
    addi    x1, x1, 8           # 栈回收
ret:
    jalr    x0, x5, 0           # 返回 (返回地址在 x5)
