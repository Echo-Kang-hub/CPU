# keyboard_vga_complete.asm
# 完整的键盘VGA测试程序（包含转换表）
# 可以通过RISC-V汇编器直接编译为机器码

.text
.globl _start

# ============================================
# 寄存器分配:
# x5  (t0): 转换表源地址指针 (ROM地址0x100)
# x6  (t1): 转换表目标地址指针 (RAM地址0x00)
# x7  (t2): 循环计数器 (64次)
# x8  (t3): 临时值
# x9  (t4): KBD_STATUS地址 (0xFFFF0014)
# x10 (t5): KBD_DATA地址 (0xFFFF0010)
# x11 (t6): VGA_BASE地址 (0xFFFF0020)
# x12 (s0): VGA显示位置偏移
# x13 (s1): ASCII码
# x14 (s2): VGA写入地址
# ============================================

_start:
    # ========================================
    # 阶段1: 初始化转换表
    # 将转换表从ROM(0x100)复制到RAM(0x00)
    # ========================================

    # 设置源地址 x5 = 0x100 (转换表在ROM中的地址)
    lui  x5, 0x00000
    addi x5, x5, 0x100

    # 设置目标地址 x6 = 0 (RAM起始地址)
    addi x6, x0, 0

    # 设置循环次数 x7 = 64 (256字节 / 4字节 = 64次)
    addi x7, x0, 64

init_loop:
    lw   x8, 0(x5)          # 从ROM读取4字节
    sw   x8, 0(x6)          # 写入RAM
    addi x5, x5, 4          # 源地址+4
    addi x6, x6, 4          # 目标地址+4
    addi x7, x7, -1         # 计数器-1
    bne  x7, x0, init_loop  # 如果x7!=0，继续循环

    # ========================================
    # 阶段2: 初始化I/O地址
    # ========================================

    # KBD_STATUS = 0xFFFF0014
    lui  x9, 0xFFFFF
    addi x9, x9, 0x014

    # KBD_DATA = 0xFFFF0010
    lui  x10, 0xFFFFF
    addi x10, x10, 0x010

    # VGA_BASE = 0xFFFF0020
    lui  x11, 0xFFFFF
    addi x11, x11, 0x020

    # VGA位置偏移 = 0
    addi x12, x0, 0

    # ========================================
    # 阶段3: 主循环 - 轮询键盘
    # ========================================

poll_loop:
    lw   x8, 0(x9)          # 读取键盘状态 [KBD_STATUS]
    andi x8, x8, 1          # 检查bit0 (是否有按键)
    beq  x8, x0, poll_loop  # 如果没有按键，继续轮询

    lw   x8, 0(x10)         # 读取扫描码 [KBD_DATA]
    
    # 检查是否是Break code (0xF0)
    addi x15, x0, 0xF0
    beq  x8, x15, skip_break
    
    # 检查是否是Shift键 (0x12 或 0x59)
    addi x15, x0, 0x12
    beq  x8, x15, poll_loop  # 跳过Shift按下
    addi x15, x0, 0x59
    beq  x8, x15, poll_loop  # 跳过Shift按下
    
    # 查表并显示
    lbu  x13, 0(x8)         # 查表: ASCII = RAM[扫描码]
    add  x14, x11, x12      # 计算VGA写入地址
    sb   x13, 0(x14)        # 写入VGA显示
    addi x12, x12, 1        # 显示位置+1
    j    poll_loop          # 返回循环

skip_break:
    # 等待下一个字节（被释放的键码）并丢弃
    lw   x8, 0(x9)          # 读取键盘状态
    andi x8, x8, 1
    beq  x8, x0, skip_break # 等待数据
    lw   x8, 0(x10)         # 读取并丢弃键码
    j    poll_loop          # 返回循环

